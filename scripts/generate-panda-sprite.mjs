const WHITE = '#f6f3ee'
const BLACK = '#1c1917'
const NOSE = '#3d3936'
const PINK = '#efb3c2'

const palette = {
  '.': null,
  w: WHITE,
  b: BLACK,
  n: NOSE,
  p: PINK,
}

function empty() {
  return Array.from({ length: 32 }, () => Array(32).fill(null))
}

function paint(grid, ox, oy, art, map = palette) {
  const rows = art
    .trim()
    .split('\n')
    .map((row) => row.trimEnd())
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      const color = map[row[x]]
      if (!color) continue
      const gx = ox + x
      const gy = oy + y
      if (gy >= 0 && gy < 32 && gx >= 0 && gx < 32) grid[gy][gx] = color
    }
  })
}

function flip(grid) {
  return grid.map((row) => [...row].reverse())
}

function shift(grid, dx, dy) {
  const next = empty()
  for (let y = 0; y < 32; y += 1) {
    for (let x = 0; x < 32; x += 1) {
      const nx = x + dx
      const ny = y + dy
      if (nx >= 0 && nx < 32 && ny >= 0 && ny < 32) next[ny][nx] = grid[y][x]
    }
  }
  return next
}

