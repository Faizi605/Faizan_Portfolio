PAL = {
    "w": (255, 255, 255, 255),
    "b": (36, 36, 36, 255),
    "n": (36, 36, 36, 255),
    "e": (255, 255, 255, 255),
    ".": (0, 0, 0, 0),
}


def parse(art):
    rows = [row.rstrip("\n") for row in art.strip("\n").split("\n")]
    if len(rows) != 32 or any(len(row) != 32 for row in rows):
        raise ValueError(f"bad art {len(rows)} x {len(rows[0]) if rows else 0}")
    img = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            px[x, y] = PAL.get(ch, (0, 0, 0, 0))
    return img


def flip(img):
    return img.transpose(Image.FLIP_LEFT_RIGHT)


def outline(img):
    src = img.load()
    out = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    dst = out.load()
    white = (255, 255, 255, 255)
    for y in range(32):
        for x in range(32):
            r, g, b, a = src[x, y]
            if a > 0:
                dst[x, y] = (r, g, b, a)
                continue
            for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
                if 0 <= nx < 32 and 0 <= ny < 32 and src[nx, ny][3] > 0:
                    dst[x, y] = white
                    break
    return out


